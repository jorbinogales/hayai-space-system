-- 035_competidores: «Radar de competidores» del Feed. Una ficha por competidor comercial de HAYAI (qué vende, precio, mensaje, a quién le habla,
-- fortaleza y debilidad frente a HAYAI). Es DISTINTO de mk_competidores (Marketing/SEO: dominio, keywords, anuncios). Lo aplica server/db/migrate.mjs
-- dentro de una transacción; no lo edites una vez aplicado. La semilla (los 12 de la investigación del 17 oct 2026) es idempotente: el índice único por
-- nombre hace que volver a correrla no duplique nada.
CREATE TABLE competidores (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  nombre      text NOT NULL CHECK (char_length(nombre) BETWEEN 1 AND 120),
  nombre_norm text NOT NULL,
  web         text CHECK (web IS NULL OR char_length(web) <= 300),
  grupo       text NOT NULL CHECK (grupo IN ('saas_venezolano', 'gratis_offline', 'software_factory', 'restaurant_tech')),
  que_vende   text CHECK (que_vende IS NULL OR char_length(que_vende) <= 400),
  precio      text CHECK (precio IS NULL OR char_length(precio) <= 300),
  mensaje     text CHECK (mensaje IS NULL OR char_length(mensaje) <= 400),
  a_quien     text CHECK (a_quien IS NULL OR char_length(a_quien) <= 300),
  fortaleza   text CHECK (fortaleza IS NULL OR char_length(fortaleza) <= 400),
  debilidad   text CHECK (debilidad IS NULL OR char_length(debilidad) <= 400),
  notas       text CHECK (notas IS NULL OR char_length(notas) <= 4000),
  orden       integer NOT NULL DEFAULT 0,
  created_by  uuid REFERENCES users (id) ON DELETE SET NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX competidores_nombre_idx ON competidores (nombre_norm);
CREATE INDEX competidores_grupo_idx ON competidores (grupo, orden);

